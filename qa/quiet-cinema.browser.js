async page => {
  const check = (condition, message) => { if (!condition) throw new Error(message) }
  const requests = []
  page.on('request', request => requests.push(request.url()))
  await page.clock.install()
  await page.setViewportSize({ width: 390, height: 620 })
  await page.goto('http://127.0.0.1:4190/')
  const featured = page.locator('.feature-link')
  const firstTitle = featured.locator('h2')
  const movies = page.locator('[data-shelf="movie"]')
  await movies.locator('a').first().waitFor()
  check(await page.locator('.shelf h2').allTextContents().then(labels => labels.join(', '))
    === 'Popular Movies, Popular Series, Top Rated Movies, Animation, K-Dramas', 'Home shows five catalogue sections')
  const visible = await movies.locator('h3').first().boundingBox()
  const tabs = await page.locator('.tab-bar').boundingBox()
  check(visible.y + visible.height < tabs.y, 'A catalogue title fits above the tab bar at 390 × 620')
  check(await featured.locator('img').getAttribute('fetchpriority') === 'high', 'The first hero image gets priority')
  check(await featured.locator('img').evaluate(img => img.decode().then(() => img.naturalWidth > 0)), 'The artwork decodes')

  check(await firstTitle.textContent() === 'In the Mood for Love', 'The opening editorial title is visible')
  if (await page.evaluate(() => navigator.maxTouchPoints > 0)) await page.touchscreen.tap(360, 95)
  check(new URL(page.url()).pathname === '/', 'The editorial whitespace is not a link')
  await page.clock.fastForward(7_500)
  check(await firstTitle.textContent() === 'Perfect Days', 'The carousel rotates on its own')
  await page.getByRole('button', { name: 'Show Past Lives' }).click()
  await page.mouse.move(380, 550)
  await page.clock.fastForward(15_000)
  check(await firstTitle.textContent() === 'Past Lives', 'Pagination pauses rotation at the selected title')
  await page.getByRole('button', { name: 'Resume featured carousel' }).click()
  await page.mouse.move(380, 550)

  if (await page.evaluate(() => navigator.maxTouchPoints > 0)) {
    const touch = await page.context().newCDPSession(page)
    await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 217, y: 188 }] })
    await page.clock.fastForward(7_500)
    check(await firstTitle.textContent() === 'Past Lives', 'Rotation waits for the gesture to finish')
    await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 67, y: 188 }] })
    await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    check(await firstTitle.textContent() === 'Once Upon a Time in the West', 'A swipe changes the featured title')
    check(new URL(page.url()).pathname === '/', 'A swipe does not open the title')
    await touch.detach()
  } else {
    await page.getByRole('button', { name: 'Show Once Upon a Time in the West' }).click()
  }

  await page.setViewportSize({ width: 320, height: 620 })
  check(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth), 'The narrow viewport has no page overflow')
  const titleBox = await firstTitle.boundingBox()
  const controls = await page.locator('.feature-controls').boundingBox()
  const titlePadding = await firstTitle.evaluate(el => parseFloat(getComputedStyle(el).paddingBottom))
  check(titleBox.y + titleBox.height - titlePadding <= controls.y, 'Long title clears the carousel controls')
  await page.setViewportSize({ width: 390, height: 620 })

  const scrollLeft = await movies.evaluate(el => { el.scrollLeft = 236; return el.scrollLeft })
  const selected = movies.locator('a').nth(2)
  const selectedTitle = await selected.locator('h3').textContent()
  await selected.click()
  await page.getByRole('heading', { name: selectedTitle, exact: true }).waitFor()
  await page.goBack()
  await movies.locator('a').first().waitFor()
  check(await movies.evaluate(el => el.scrollLeft) === scrollLeft, 'Back restores the carousel row position')
  check(await firstTitle.textContent() === 'Once Upon a Time in the West', 'Back restores the featured title')
  await page.clock.fastForward(15_000)
  check(await firstTitle.textContent() === 'Once Upon a Time in the West', 'Back preserves the rotation preference')

  const drama = page.locator('[data-shelf="k-dramas"] a').first()
  await drama.scrollIntoViewIfNeeded()
  const discoveryScroll = await page.evaluate(() => scrollY)
  await drama.click()
  await page.getByRole('heading', { name: 'Crash Landing on You', exact: true }).waitFor()
  await page.goBack()
  await page.waitForFunction(y => scrollY === y, discoveryScroll)

  await page.getByRole('link', { name: 'Search', exact: true }).click()
  const input = page.getByRole('searchbox', { name: 'Search movies and series' })
  check(await input.evaluate(el => el === document.activeElement), 'Search opens with focus in the field')
  await input.fill('Nobody Wants This')
  await page.clock.fastForward(400)
  const result = page.locator('.title-card').filter({ has: page.getByRole('heading', { name: 'Nobody Wants This', exact: true }) }).first()
  await result.waitFor()
  await result.click()
  await page.getByRole('heading', { name: 'Nobody Wants This', exact: true }).waitFor()
  await page.getByRole('link', { name: 'Search', exact: true }).click()
  await page.getByRole('link', { name: 'Nobody Wants This', exact: true }).waitFor()
  await page.getByRole('link', { name: 'Movies', exact: true }).click()
  await page.getByRole('heading', { name: 'Movies', exact: true }).waitFor()
  await page.getByRole('link', { name: 'Series', exact: true }).click()
  await page.getByRole('heading', { name: 'Series', exact: true }).waitFor()
  check(!requests.some(url => /circleftp|\/api\/play[?]/.test(url)), 'Discovery and title details request no Circle source')
  return 'Quiet Cinema viewport, gestures, navigation, and search checks passed'
}
